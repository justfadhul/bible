/**
 * The app's name, in one place.
 *
 * Manna, from Exodus 16: gathered fresh each morning, exactly one day's worth,
 * and it could not be kept overnight — anyone who tried found it spoiled. That
 * is this app's rule rather than a decoration on top of it. One spin a day,
 * binding, no stockpiling, and the same portion for everyone reading together.
 */
export const APP_NAME = 'Manna'
export const APP_TAGLINE = 'A daily portion of Scripture, gathered together.'
export const APP_DESCRIPTION =
  'Spin once a day, read whatever comes up, and talk about it. Neither of you chooses, and no passage returns until all 286 have been read.'

